এআই হ্যালুসিনেশনকে তাই শুধু ভুল উত্তর হিসেবে দেখলে বিষয়টি ছোট করে দেখা হয়। আসল সমস্যা হলো ভুল তথ্যের সঙ্গে উচ্চ আত্মবিশ্বাসের একটি অস্বস্তিকর সমন্বয়। একজন মানুষ ভুল করলে সাধারণত দ্বিধা, অসম্পূর্ণ স্মৃতি বা অনিশ্চয়তা প্রকাশ করতে পারে। ভাষা মডেল সবসময় এমন সংকেত দেয় না।

## ChatGPT কেন ভুল তথ্য দেয়?

প্রথম কারণ, ভাষা মডেলের মূল কাজ হলো ভাষা তৈরি করা। একটি মডেলকে যদি প্রশ্ন করা হয় আগামীকাল কোন ছোট প্রতিষ্ঠানের প্রধান কে, তাহলে সে আগে থেকে সেই তথ্য নির্ভুলভাবে সংরক্ষিত আছে কি না তা পরীক্ষা করে না। তার প্রশিক্ষণ থেকে পাওয়া ভাষাগত সম্পর্ক ব্যবহার করে সবচেয়ে সম্ভাব্য উত্তর তৈরি করতে পারে।

দ্বিতীয় কারণ হলো তথ্যের সীমাবদ্ধতা। কোনো বিষয় নিয়ে পর্যাপ্ত নির্ভরযোগ্য তথ্য না থাকলে, মডেল শূন্যস্থান পূরণ করার চেষ্টা করতে পারে। বিশেষ করে বিরল ব্যক্তি, পুরোনো ওয়েবসাইট, স্থানীয় প্রতিষ্ঠান, সাম্প্রতিক ঘটনা বা অল্প আলোচিত গবেষণার ক্ষেত্রে এই ঝুঁকি বাড়ে।

তৃতীয় কারণ হলো মূল্যায়নের কাঠামো। ওপেনএআইয়ের বিশ্লেষণে একটি গুরুত্বপূর্ণ বিষয় উঠে এসেছে: অনেক মূল্যায়ন ব্যবস্থায় সঠিক উত্তর না জানার চেয়ে উত্তর দেওয়াকে বেশি পুরস্কৃত করা হয়েছে। ফলে একটি মডেল কখনো কখনো জানি না বলার বদলে অনুমান করে। urlhttps://openai.com/index/why-language-models-hallucinate/

## কোন কাজে ঝুঁকি বেশি?

কম ঝুঁকির কাজে একটি ভুল উত্তর বিরক্তিকর হতে পারে। যেমন কোনো সফটওয়্যারের সাধারণ ফিচারের নাম ভুল বলা। কিন্তু গবেষণা, আইন, চিকিৎসা, আর্থিক সিদ্ধান্ত বা সাংবাদিকতায় একই আচরণ গুরুতর সমস্যা তৈরি করতে পারে।

বিশেষ করে উদ্ধৃতি ও সূত্রের ক্ষেত্রে সতর্ক হওয়া দরকার। এআই এমন গবেষণাপত্রের নাম, ডিওআই, বই বা ওয়েবসাইট তৈরি করতে পারে যার অস্তিত্ব নেই। তাই কোনো সূত্র শুধু এআই দিয়েছে বলে গ্রহণ করা যাবে না। মূল প্রকাশনা, জার্নাল বা প্রতিষ্ঠানের ওয়েবসাইটে গিয়ে যাচাই করতে হবে।

## একটি সহজ যাচাই পদ্ধতি

গুরুত্বপূর্ণ কোনো তথ্য এআই থেকে নেওয়ার আগে পাঁচটি প্রশ্ন করা যায়। তথ্যটির মূল উৎস কী? উৎসটি বাস্তবে আছে কি? একই তথ্য অন্য স্বাধীন উৎসে পাওয়া যাচ্ছে কি? তারিখটি ঠিক আছে কি? এবং মডেল কি নির্দিষ্ট প্রমাণ দেখাচ্ছে, নাকি শুধু একটি সুন্দর ব্যাখ্যা দিচ্ছে?

গবেষণার ক্ষেত্রে সবচেয়ে ভালো পদ্ধতি হলো এআইকে তথ্যের চূড়ান্ত উৎস না বানিয়ে গবেষণার সহকারী হিসেবে ব্যবহার করা। এআই দিয়ে সম্ভাব্য সূত্র খোঁজা যেতে পারে, বিষয় ভাগ করা যেতে পারে, জটিল লেখা সহজ করা যেতে পারে। কিন্তু চূড়ান্ত উদ্ধৃতি দিতে হলে মূল উৎসে ফিরতে হবে।

