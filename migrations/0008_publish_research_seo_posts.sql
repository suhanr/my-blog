সবার আগে আসে পরিচয়-সংক্রান্ত তথ্য: জাতীয় পরিচয়পত্র নম্বর, পাসপোর্ট, ফোন নম্বর, ব্যক্তিগত ঠিকানা, পাসওয়ার্ড, ব্যাংক বা মোবাইল ফাইন্যান্সিয়াল সার্ভিসের তথ্য। এরপর আসে স্বাস্থ্য, চাকরি, পারফরম্যান্স, গবেষণায় অংশগ্রহণকারীর তথ্য এবং প্রতিষ্ঠানের গোপন নথি।

একটি সাধারণ ভুল হলো পুরো ডেটাসেট এআইতে তুলে দিয়ে পরে কিছু রেকর্ড মুছে দেওয়া। এতে ঝুঁকি কমে না, কারণ শুরুতেই প্রয়োজনের চেয়ে বেশি তথ্য শেয়ার করা হয়েছে। গবেষণায় বিশেষ করে উত্তরদাতার নাম, ফোন নম্বর, ই-মেইল, লোকেশন বা ইউনিক আইডি আলাদা করে রাখাই নিরাপদ।

## এআইতে ডেটা দিলে কি তা অবশ্যই প্রশিক্ষণে চলে যায়?

এমন সরল উত্তর নেই। কোনো সেবায় ব্যবহারকারীর ডেটা মডেল উন্নয়নে ব্যবহার হতে পারে, কোনো সেবায় সেটি বন্ধ করার অপশন থাকতে পারে, আবার এন্টারপ্রাইজ প্ল্যানে আলাদা নীতি থাকতে পারে। তাই অনুমান না করে নির্দিষ্ট সেবার প্রাইভেসি ও ডেটা ব্যবহার নীতি দেখা উচিত।

আইসিও সতর্ক করেছে, জেনারেটিভ এআই মডেল তৈরির ক্ষেত্রে ওয়েব থেকে সংগৃহীত ব্যক্তিগত তথ্য, প্রশিক্ষণ ডেটা এবং ব্যবহারকারীর প্রম্পট সবই তথ্য সুরক্ষার প্রশ্ন তৈরি করতে পারে। urlhttps://ico.org.uk/about-the-ico/what-we-do/our-work-on-artificial-intelligence/generative-ai-fourth-call-for-evidence/

## গবেষণা ডেটার ক্ষেত্রে নিয়ম আরও কঠোর

গবেষকরা প্রায়ই কাঁচা ডেটা নিয়ে কাজ করেন। ধরুন একটি জরিপে ৫০০ জন উত্তরদাতা আছে। ডেটাসেটের নাম, ফোন নম্বর এবং উত্তরগুলো একসঙ্গে থাকলে এটি সরাসরি ব্যক্তিগত তথ্যের ঝুঁকি তৈরি করতে পারে। এআই দিয়ে ডেটা পরিষ্কার বা বিশ্লেষণ করার আগে ডেটা মিনিমাইজেশন, ছদ্মনামকরণ এবং প্রয়োজনহীন কলাম বাদ দেওয়ার মতো পদক্ষেপ নেওয়া উচিত।

একই নিয়ম অফিসের ক্ষেত্রেও প্রযোজ্য। একটি কর্মীর মূল্যায়ন রিপোর্ট বা ক্লায়েন্ট ডেটা কপি করে পাবলিক এআই সেবায় দেওয়া শুধুই প্রযুক্তিগত সিদ্ধান্ত নয়; এটি প্রতিষ্ঠানের তথ্য-শাসনের সিদ্ধান্ত।

## নিরাপদ ব্যবহারের একটি বাস্তব পদ্ধতি

প্রথমে ডেটাকে তিন স্তরে ভাগ করা যায়: প্রকাশ্য, অভ্যন্তরীণ এবং সংবেদনশীল। প্রকাশ্য তথ্য সাধারণ এআই টুলে দেওয়া তুলনামূলক কম ঝুঁকির। অভ্যন্তরীণ তথ্য দিলে প্রতিষ্ঠানের নীতিমালা ও সেবার ডেটা ব্যবহারের শর্ত দেখতে হবে। সংবেদনশীল তথ্য সাধারণত সরাসরি দেওয়া উচিত নয়।

তারপর প্রয়োজনের অতিরিক্ত তথ্য বাদ দিতে হবে। পুরো রিপোর্ট দেওয়ার বদলে প্রয়োজনীয় কয়েকটি অনামিকৃত উদাহরণ দেওয়া যায়। ব্যক্তির নামের জায়গায় রেসপন্ডেন্ট-০০১, রেসপন্ডেন্ট-০০২ ব্যবহার করা যায়। সরাসরি শনাক্তকারী ভেরিয়েবল সরিয়ে দেওয়া যায়।

সবশেষে সবচেয়ে গুরুত্বপূর্ণ নীতি হলো: এআইকে সহকারী হিসেবে ব্যবহার করুন, ডেটার মালিক হিসেবে নয়। এআই একটি শক্তিশালী বিশ্লেষণ যন্ত্র, কিন্তু কোনো প্রতিষ্ঠানের তথ্য-শাসন কাঠামোর বিকল্প নয়।

