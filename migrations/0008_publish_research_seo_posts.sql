ভালো পদ্ধতি হলো নিজের কাঁচা তথ্য আগে লেখা। কোথায় কাজ করেছেন, কী দায়িত্ব ছিল, কোন সফটওয়্যার ব্যবহার করেছেন, কতজনের সঙ্গে কাজ করেছেন, কী ফলাফল তৈরি হয়েছে, কোন প্রকল্পে কী ভূমিকা ছিল এসব তথ্য এআইকে দিন। এরপর বলুন, তথ্য না বদলে এগুলোকে সংক্ষিপ্ত ও নির্দিষ্ট ভাষায় সাজাতে।

## কাজের ফলাফল দেখান

সিভিতে শুধু দায়িত্ব লিখলে প্রভাব কমে। ধরুন লিখলেন, গবেষণা প্রকল্পে ডেটা সংগ্রহ করেছি। এর চেয়ে ভালো হলো, ৪০০+ উত্তরদাতার জরিপের জন্য ডিজিটাল ডেটা সংগ্রহের ফর্ম তৈরি ও মাঠ পর্যায়ের তথ্য-গুণগত মান যাচাই করেছি। এখানে কাজের পরিমাণ এবং ফল দুটোই বোঝা যায়।

এআই এই রূপান্তরে সাহায্য করতে পারে। কিন্তু সংখ্যা বানিয়ে দেওয়া যাবে না। আপনি যদি ৪০টি প্রকল্প না করেন, এআইকে ৪০ লিখতে দেবেন না। একটি চাকরির জন্য মিথ্যা অভিজ্ঞতা যোগ করা স্বল্পমেয়াদে সুন্দর দেখালেও সাক্ষাৎকারে সহজেই ধরা পড়তে পারে।

