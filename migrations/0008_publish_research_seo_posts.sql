## Confidence level ও margin of error কী?

Confidence level যত বেশি, একই precision রাখতে সাধারণত sample size তত বেশি লাগে। আবার margin of error ছোট করতে চাইলে sample size বাড়ে। অর্থাৎ ৯৫ শতাংশ confidence ও ±৫ শতাংশ error-এর বদলে ±৩ শতাংশ error চাইলে অনেক বেশি completed response দরকার হবে।

এখানে একটি গুরুত্বপূর্ণ বিষয় হলো confidence level sample-এর প্রতিনিধিত্বের গ্যারান্টি নয়। যদি sampling method biased হয়, sample বড় করেও সেই bias দূর করা যায় না। একটি convenience sample-এ ৫,০০০ উত্তরদাতা থাকলেও সেটি random probability sample-এর মতো প্রতিনিধিত্বশীল নাও হতে পারে।

