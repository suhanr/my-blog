## Design effect এবং subgroup

Cluster sampling বা complex survey design ব্যবহার করলে simple random sample-এর formula সরাসরি যথেষ্ট নাও হতে পারে। design effect sample size বাড়াতে পারে। আবার আপনি যদি নারী-পুরুষ, শহর-গ্রাম বা কয়েকটি জেলাকে আলাদাভাবে তুলনা করতে চান, তাহলে প্রতিটি subgroup-এর জন্য পর্যাপ্ত observation দরকার হতে পারে।

এই কারণে sample size শুধু একটি calculator-এর output নয়। এটি research design-এর অংশ। প্রথমে primary outcome নির্ধারণ করতে হয়, তারপর statistical precision, sampling method এবং বাস্তব মাঠপর্যায়ের constraint বিবেচনা করতে হয়।

সবচেয়ে গুরুত্বপূর্ণ শিক্ষা হলো: sample size বড় হলেই গবেষণা ভালো হয় না। সঠিক population, সঠিক sampling strategy এবং পরিষ্কার research question ছাড়া বড় sample শুধু বড় dataset তৈরি করে।

