অনেক জরিপে ৯৫ শতাংশ confidence level এবং ±৫ শতাংশ margin of error ব্যবহার করলে large population-এর জন্য প্রায় ৩৮৪টি completed response পাওয়া যায়। এই হিসাবের পেছনে একটি প্রচলিত formula আছে:

`n = Z² × p × (1-p) / E²`

এখানে n হলো প্রয়োজনীয় sample size, Z হলো confidence level-এর মান, p হলো expected proportion এবং E হলো margin of error। ৯৫ শতাংশ confidence-এর জন্য Z প্রায় ১.৯৬। p জানা না থাকলে ০.৫ নেওয়া হয়, কারণ এতে প্রয়োজনীয় sample size সর্বোচ্চ হয়। এই পদ্ধতির ব্যাখ্যা survey methodology এবং statistics-এর পাঠ্যসূত্রে নিয়মিত ব্যবহৃত হয়। urlhttps://online.stat.psu.edu/stat800/Lesson04

## Population ছোট হলে কী হবে?

